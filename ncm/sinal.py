"""Existe dinheiro nas fotos? Checagem antes de insistir no NCM (task 7 do ncm-live-trading.md).

Para cada minuto o simulador dá o resultado exato de 8 entradas (comprado/vendido x 5/15/30/45 min, taxa e
slippage). Um modelo simples (ridge e MLP) prevê esses 8 resultados a partir da foto; em junho o bot entra na
melhor opção prevista se ela passar de um limiar, uma posição por vez, como no ao vivo (`treino.opera`).
Treino fev–mai, escolha em junho; o teste segue fechado.

    ~/.local/share/wow-voz/venv/bin/python -I ncm/sinal.py
"""
import sys
from pathlib import Path

import numpy as np
import torch

AQUI = Path(__file__).resolve().parent
sys.path.insert(0, str(AQUI))
import rotulos as rt  # noqa: E402
import treino as tn  # noqa: E402

DURACOES = [5, 15, 30, 45]
ACOES = [(lado, dur) for lado in (1, -1) for dur in DURACOES]
LIMIARES = [0.0, 0.0005, 0.001, 0.002, 0.003]  # resultado previsto mínimo para entrar (fração)
WIKI = AQUI.parent / "wiki/project-system/signal-check-btc.md"


def resultados(ab: np.ndarray) -> np.ndarray:
    """(N, 8): log do capital de cada entrada."""
    n = len(ab)
    return np.stack([rt.recompensa_lote(ab, np.full(n, lado), np.full(n, dur)) for lado, dur in ACOES], 1)


def ridge(X: np.ndarray, Y: np.ndarray, lam: float = 100.0):
    Xb = np.c_[X, np.ones(len(X))]
    W = np.linalg.solve(Xb.T @ Xb + lam * np.eye(Xb.shape[1]), Xb.T @ Y)
    return lambda Z: np.c_[Z, np.ones(len(Z))] @ W


def mlp(X: np.ndarray, Y: np.ndarray, epocas: int = 6):
    torch.manual_seed(0)
    net = torch.nn.Sequential(torch.nn.Linear(X.shape[1], 256), torch.nn.GELU(), torch.nn.Dropout(0.2),
                              torch.nn.Linear(256, 256), torch.nn.GELU(), torch.nn.Linear(256, Y.shape[1])).cuda()
    opt = torch.optim.AdamW(net.parameters(), lr=1e-3, weight_decay=1e-2)
    Xt, Yt = torch.from_numpy(X).cuda(), torch.from_numpy((Y * 1000).astype(np.float32)).cuda()
    for _ in range(epocas):
        net.train()
        for i in torch.randperm(len(Xt), device="cuda").split(1024):
            perda = torch.nn.functional.huber_loss(net(Xt[i]), Yt[i])
            opt.zero_grad(set_to_none=True)
            perda.backward()
            opt.step()
    net.eval()

    @torch.no_grad()
    def prever(Z: np.ndarray) -> np.ndarray:
        return np.concatenate([net(torch.from_numpy(Z[i:i + 8192]).cuda()).cpu().numpy()
                               for i in range(0, len(Z), 8192)]) / 1000
    return prever


def linhas(nome: str, periodo: str, prev: np.ndarray, real: np.ndarray, parte: dict, funding: dict) -> list[str]:
    melhor = prev.argmax(1)
    lado = np.array([ACOES[a][0] for a in melhor])
    dur = np.array([ACOES[a][1] for a in melhor])
    conf = prev.max(1)
    escolhido = real[np.arange(len(real)), melhor]
    top = escolhido[conf >= np.quantile(conf, 0.99)].mean()  # 1% de minutos com maior previsão
    out = [f"| {nome} | {periodo} | 1% mais confiante: {100 * top:+.3f}%/entrada | – | – | – | – |"]
    for limiar in LIMIARES:
        m = tn.opera(parte, lado, dur, conf, limiar, funding)
        if not m["n"]:
            out.append(f"| {nome} | {periodo} | limiar {100 * limiar:.2f}% | 0 | – | – | – |")
            continue
        out.append(f"| {nome} | {periodo} | limiar {100 * limiar:.2f}% | {m['n']} ({m['long']}L/{m['short']}S) | "
                   f"{m['pf']:.2f} | {100 * m['composto']:+.2f}% | {100 * m['dd']:.1f}% |")
    return out


def main() -> int:
    d = tn.dados()
    tr, v = d["treino"], d["val"]
    Ytr, Yv = resultados(tr["ab"]), resultados(v["ab"])
    print("melhor entrada em retrospecto > 0 em", f"{(Ytr.max(1) > 0).mean():.0%} dos minutos de treino", flush=True)
    saida = []
    for nome, fabrica in (("ridge", ridge), ("mlp", mlp)):
        prever = fabrica(tr["X"], Ytr)
        for periodo, parte, Y in (("fev–mai (dentro)", tr, Ytr), ("jun (fora)", v, Yv)):
            saida += linhas(nome, periodo, prever(parte["X"]), Y, parte, d["funding"])
            print("\n".join(saida[-len(LIMIARES) - 1:]), flush=True)
    WIKI.write_text(_pagina(saida))
    print(f"-> {WIKI}")
    return 0


